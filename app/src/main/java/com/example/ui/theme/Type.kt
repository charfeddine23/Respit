/**
 * Returns a responsive SP value adjusting automatically based on the device's smallest width (sw600dp tablet vs phone).
 */
@Composable
fun responsiveSp(phoneSp: TextUnit, tabletSp: TextUnit): TextUnit {
    val config = LocalConfiguration.current
    return if (config.smallestScreenWidthDp >= 600) tabletSp else phoneSp
}
